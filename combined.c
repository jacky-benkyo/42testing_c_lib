int	ft_memcmp(const void *dest, const void *src, size_t n)
{
	unsigned char	*m;
	unsigned char	*p;
	size_t			l;

	if ((!src && !dest) || (n == 0))
		return (0);
	m = (unsigned char *) src;
	p = (unsigned char *) dest;
	l = 0;
	while (l < n)
	{
		if (m[l] != p[l])
			return (((unsigned char)p[l]) - ((unsigned char)m[l]));
		l++;
	}
	return (0);
}
