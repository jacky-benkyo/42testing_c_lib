void	*ft_memcpy(void *dest, const void *src, size_t n)
{
	unsigned char	*m;
	unsigned char	*p;
	size_t			l;

	if (!src && !dest)
		return (NULL);
	l = 0;
	m = (unsigned char *) src;
	p = (unsigned char *) dest;
	while (l < n)
	{
		p[l] = m[l];
		l++;
	}
	return ((void *) dest);
}
