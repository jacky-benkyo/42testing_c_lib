void	*ft_calloc(size_t nelem, size_t elsize)
{
	size_t			i;
	unsigned char	*p;

	if (nelem != 0 && elsize != 0)
	{
		if (nelem > ((size_t) - 1) / elsize)
			return (NULL);
	}
	i = 0;
	p = malloc(nelem * elsize);
	if (!p)
		return (NULL);
	while (i < (nelem * elsize))
	{
		p[i] = 0;
		i++;
	}
	return ((void *)p);
}
