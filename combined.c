void	*ft_memmove(void *dest, const void *src, size_t n)
{
	unsigned char	*m;
	unsigned char	*p;
	size_t			l;

	if (!src && !dest)
		return (NULL);
	m = (unsigned char *) src;
	p = (unsigned char *) dest;
	l = 0;
	if (p > m)
	{
		while (0 < n--)
			p[n] = m[n];
	}
	else
	{
		while (n > l++)
			p[l - 1] = m[l - 1];
	}
	return ((void *)dest);
}
